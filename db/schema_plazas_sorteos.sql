            RAISE;
        END IF;
END;
/

-- 4. TABLA TRP_BOLETAS — Verificar/Actualizar
-- Asegura que la FK apunte a CNL_SORTEOS y que LOTE_ORIGEN exista.
-- =============================================================================
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE TRP_BOLETAS (
        ID_BOLETA         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ID_SORTEO         NUMBER,
        NUMERO_BOLETA     VARCHAR2(20 BYTE) NOT NULL,
        NUMEROS_OPORTUNIDADES VARCHAR2(500 BYTE),
        QR_TOKEN          VARCHAR2(100 BYTE) NOT NULL,
        ESTADO_REDENCION  VARCHAR2(20 BYTE) DEFAULT ''NO_CONSULTADA'',
        FECHA_GENERACION  TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
        LOTE_ORIGEN       VARCHAR2(50 BYTE),
        CONSTRAINT UK_BOLETA_QR UNIQUE (QR_TOKEN),
        CONSTRAINT FK_BOLETA_SORTEO FOREIGN KEY (ID_SORTEO)
            REFERENCES CNL_SORTEOS(ID_SORTEO)
    )';
    DBMS_OUTPUT.PUT_LINE('Tabla TRP_BOLETAS creada.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Tabla TRP_BOLETAS ya existe. Verificando columnas...');
            -- Agregar LOTE_ORIGEN y NUMEROS_OPORTUNIDADES si no existen
            BEGIN
                EXECUTE IMMEDIATE 'ALTER TABLE TRP_BOLETAS ADD (LOTE_ORIGEN VARCHAR2(50 BYTE))';
                DBMS_OUTPUT.PUT_LINE('  Columna LOTE_ORIGEN agregada.');
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE = -1430 THEN
                        DBMS_OUTPUT.PUT_LINE('  Columna LOTE_ORIGEN ya existe.');
                    ELSE
                        RAISE;
                    END IF;
            END;
            BEGIN
                EXECUTE IMMEDIATE 'ALTER TABLE TRP_BOLETAS ADD (NUMEROS_OPORTUNIDADES VARCHAR2(500 BYTE))';
                DBMS_OUTPUT.PUT_LINE('  Columna NUMEROS_OPORTUNIDADES agregada.');
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE = -1430 THEN
                        DBMS_OUTPUT.PUT_LINE('  Columna NUMEROS_OPORTUNIDADES ya existe.');
                    ELSE
                        RAISE;
                    END IF;
            END;
        ELSE
            RAISE;
        END IF;
END;
/

