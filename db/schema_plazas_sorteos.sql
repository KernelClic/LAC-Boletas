        FECHA_VIGENCIA  DATE,
        CONSTRAINT FK_RANGO_SORTEO FOREIGN KEY (ID_SORTEO)
            REFERENCES CNL_SORTEOS(ID_SORTEO),
        CONSTRAINT UK_RANGO_NUMEROS UNIQUE (ID_SORTEO, RANGO_INICIAL, RANGO_FINAL)
    )';
