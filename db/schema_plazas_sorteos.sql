-- =============================================================================
-- Script de Migración: Plazas, Sorteos y Rangos de Premio
-- Descripción: Crea las tablas CNL_PLAZAS, CNL_SORTEOS, CNL_RANGOS_PREMIO
--              y actualiza TRP_BOLETAS para soportar el modelo de plazas
--              con códigos seguros y sorteos consecutivos.
-- =============================================================================

-- 1. TABLA CNL_PLAZAS
-- Cada aplicación tiene un codigo_seguro único asignado desde la web.
-- =============================================================================
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE CNL_PLAZAS (
        ID_PLAZA       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CODIGO_SEGURO  VARCHAR2(50 BYTE) NOT NULL,
        NOMBRE         VARCHAR2(100 BYTE) NOT NULL,
        ESTADO         VARCHAR2(20 BYTE) DEFAULT ''ACTIVO'',
        FECHA_CREACION TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT UK_PLAZAS_CODIGO UNIQUE (CODIGO_SEGURO)
    )';
    DBMS_OUTPUT.PUT_LINE('Tabla CNL_PLAZAS creada.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Tabla CNL_PLAZAS ya existe.');
        ELSE
            RAISE;
        END IF;
END;
/

-- 2. TABLA CNL_SORTEOS
-- Cada sorteo pertenece a una plaza y tiene un consecutivo automático.
-- =============================================================================
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE CNL_SORTEOS (
        ID_SORTEO     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ID_PLAZA      NUMBER,
        NOMBRE_SORTEO VARCHAR2(150 BYTE) NOT NULL,
        FECHA_INICIO  DATE,
        FECHA_FIN     DATE,
        ESTADO        VARCHAR2(20 BYTE) DEFAULT ''ACTIVO'',
        CONSTRAINT FK_SORTEO_PLAZA FOREIGN KEY (ID_PLAZA)
            REFERENCES CNL_PLAZAS(ID_PLAZA)
    )';
    DBMS_OUTPUT.PUT_LINE('Tabla CNL_SORTEOS creada.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Tabla CNL_SORTEOS ya existe.');
        ELSE
            RAISE;
        END IF;
END;
/

-- 3. TABLA CNL_RANGOS_PREMIO
-- Rangos de números premiados asociados a cada sorteo.
-- =============================================================================
BEGIN
    EXECUTE IMMEDIATE '
    CREATE TABLE CNL_RANGOS_PREMIO (
        ID_RANGO        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ID_SORTEO       NUMBER NOT NULL,
        RANGO_INICIAL   NUMBER NOT NULL,
        RANGO_FINAL     NUMBER NOT NULL,
        MENSAJE_PREMIO  VARCHAR2(500 BYTE),
        PRIORIDAD       NUMBER DEFAULT 1 NOT NULL,
